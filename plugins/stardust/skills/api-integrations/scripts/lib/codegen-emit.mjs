  if (Array.isArray(value)) return value.map((entry) => cloneTemplate(entry));
  if (value && typeof value === 'object') {
    return Object.fromEntries(
      Object.entries(value).map(([key, entry]) => [key, cloneTemplate(entry)]),
    );
  }
  return value;
