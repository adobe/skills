export function emitClientModule(contract) {
  const contentType = String(contract.contentType || '').split(';')[0].trim().toLowerCase();
  const baseHeaders = {};
  if (contentType === 'application/json' || contract.graphql) baseHeaders['content-type'] = 'application/json';
  else if (contentType === 'application/x-www-form-urlencoded') baseHeaders['content-type'] = 'application/x-www-form-urlencoded';
  const accept = acceptHeader(contract);
  if (accept) baseHeaders.accept = accept;

  const constants = (contract.clientDeps || []).filter((dep) => dep.from === 'constant')
    .map(({ path, value }) => ({ path, value }));
  const clientDeps = (contract.clientDeps || []).filter((dep) => dep.from !== 'constant');
  const fields = (contract.fieldMap || []).map(({ path, name }) => ({ path, name }));
  const alias = camelAlias(contract.id);
  const query = graphqlQuery(contract);
  const persistedHash = graphqlPersistedHash(contract);
  const multipart = multipartFields(contract, contentType);

  return [
    generatedMarker(contract.id),
    "import { apiBaseFor, apiHeadersFor } from '../api-config.js';",
    '',
    `const ID = ${jsLiteral(contract.id)};`,
    `const ENDPOINT = ${jsLiteral(contract.endpoint)};`,
    `const METHOD = ${jsLiteral(String(contract.method || 'GET').toUpperCase())};`,
    `const CONTENT_TYPE = ${jsLiteral(contentType)};`,
    `const ORIGIN = ${jsLiteral(contract.origin || 'third-party')};`,
    `const AUTH_SCHEME = ${jsLiteral(contract.auth?.scheme || 'none')};`,
    `const GRAPHQL = ${contract.graphql ? 'true' : 'false'};`,
    `const GRAPHQL_OPERATION_NAME = ${jsLiteral(contract.graphql?.operationName || '')};`,
    `const GRAPHQL_QUERY = ${query ? jsLiteral(query) : 'null'};`,
    `const GRAPHQL_HASH = ${persistedHash ? jsLiteral(persistedHash) : 'null'};`,
    `const GRAPHQL_VARIABLES = ${jsLiteral(contract.graphql?.variables || {})};`,
    `const QUERY_KEYS = ${jsLiteral(queryKeys(contract))};`,
    `const REQUEST_TEMPLATE = ${jsLiteral(requestTemplate(contract))};`,
    `const FIELD_PATHS = ${jsLiteral((contract.fieldMap || []).map((entry) => entry.path))};`,
    `const MULTIPART_FIELDS = ${jsLiteral(multipart)};`,
    `const CONSTANT_DEPS = ${jsLiteral(constants)};`,
    `const CLIENT_DEPS = ${jsLiteral(clientDeps)};`,
    `const BASE_HEADERS = ${jsLiteral(baseHeaders)};`,
    '',
    `export const FIELDS = ${jsLiteral(fields)};`,
    emitGeneratedHelpers(),
    'export function buildPayload(values = {}) {',
    '  const payload = cloneTemplate(REQUEST_TEMPLATE);',
    '  FIELD_PATHS.forEach((path) => {',
    '    setPath(payload, path, valueFor(values, path));',
    '  });',
    '  CONSTANT_DEPS.forEach((dep) => {',
    '    setPath(payload, dep.path, dep.value);',
    '  });',
    '  return payload;',
    '}',
    '',
    'async function apiCall(values = {}, { signal } = {}) {',
    '  try {',
    '    const payload = await applyClientDeps(buildPayload(values));',
    '    const response = await fetch(endpointUrl(values), {',
    '      method: METHOD,',
    '      headers: requestHeaders(),',
    '      body: encodedBody(payload, values),',
    '      signal,',
    "      credentials: AUTH_SCHEME === 'cookie' ? 'include' : 'same-origin',",
    '    });',
    '    const parsed = await parseResponse(response);',
    '    return {',
    '      ok: response.ok,',
    '      status: response.status,',
    '      data: response.ok ? parsed : null,',
    '      error: response.ok ? null : parsed,',
    '    };',
    '  } catch (error) {',
    '    return { ok: false, status: 0, data: null, error: error.message || String(error) };',
    '  }',
    '}',
    '',
    `export { apiCall as ${alias} };`,
    'export default apiCall;',
    '',
  ].join('\n');
}
