#!/usr/bin/env node
/**
 * skills/deploy/scripts/martech-scaffold.mjs — martech contract → scripts/martech.js (reference/martech.md).
 *
 * Writes scripts/martech.js from the enabled parts of stardust/martech-contract.json and hooks it in:
 *   loadConsent()  the CMP, first thing in loadEager() of scripts/scripts.js
 *   loadTags()     each enabled route, from scripts/delayed.js (else loadDelayed() in scripts/scripts.js);
 *                  a route with a `category` waits until the CMP grants that consent group
 * Nothing loads off the production hosts unless the URL has `?martech=on`; `&consent=accept` then grants
 * every category. A scripts/martech.js the scaffold did not write is a conflict unless --force.
 * Re-running on the same contract changes nothing.
 *
 *   node skills/deploy/scripts/martech-scaffold.mjs [--contract stardust/martech-contract.json] [--root .]
 *        [--dry-run] [--force]
 *
 * Exit 0 written or unchanged; 1 usage error, invalid contract, conflict, or no hook point.
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

if (process.argv.includes('--help') || process.argv.includes('-h')) {
  const header = readFileSync(new URL(import.meta.url), 'utf8').match(/\/\*\*[\s\S]*?\*\//)[0];
  console.log(header.replace(/^\/\*\*\s*|\s*\*\/$/g, '').replace(/^\s*\* ?/gm, '').trim());
  process.exit(0);
}

const argv = process.argv.slice(2);
const arg = (name, dflt) => { const i = argv.indexOf(`--${name}`); return i >= 0 && argv[i + 1] && !argv[i + 1].startsWith('--') ? argv[i + 1] : dflt; };
const fail = (msg) => { console.error(`martech-scaffold: ${msg}`); process.exit(1); };

const ROOT = resolve(arg('root', '.'));
const CONTRACT = arg('contract', 'stardust/martech-contract.json');
const DRY = argv.includes('--dry-run');
const FORCE = argv.includes('--force');
const MARK = '// Generated by stardust deploy/martech-scaffold.mjs from the martech contract; re-run it.';
const CONSENT_HOOK = "import('./martech.js').then((m) => m.loadConsent());";
const TAGS_HOOK = "import('./martech.js').then((m) => m.loadTags());";

const at = (p) => join(ROOT, p);
const read = (p) => (existsSync(at(p)) ? readFileSync(at(p), 'utf8') : null);

const str = (s) => `'${JSON.stringify(s).slice(1, -1).replace(/\\"/g, '"').replace(/'/g, "\\'")}'`;
function literal(v, pad = '') {
  if (typeof v === 'string') return str(v);
  if (v === null || typeof v !== 'object') return String(v);
  const inner = `${pad}  `;
  const items = Array.isArray(v)
    ? v.map((x) => literal(x, inner))
    : Object.entries(v).map(([k, x]) => `${/^[A-Za-z_$][\w$]*$/.test(k) ? k : str(k)}: ${literal(x, inner)}`);
  const [open, close] = Array.isArray(v) ? ['[', ']'] : ['{', '}'];
  return items.length ? `${open}\n${items.map((i) => `${inner}${i},\n`).join('')}${pad}${close}` : `${open}${close}`;
}

function configOf(contract) {
  const cmp = contract.consent?.cmp || null;
  const routes = (contract.routes || []).filter((r) => r.enabled);
  const missing = cmp?.enabled && Object.entries(cmp.attrs || {}).find(([, v]) => !v);
  if (missing) fail(`consent.cmp is enabled but \`${missing[0]}\` is empty — copy the id from the CMP admin into the contract`);
  const gated = routes.find((r) => r.category && !(cmp?.groups && cmp?.event));
  if (gated) fail(`route \`${gated.id}\` has a category but the CMP exposes no consent groups — clear the category or set consent.cmp.groups/event`);
  return {
    productionHosts: contract.productionHosts || [],
    cmp: cmp && {
      enabled: !!cmp.enabled, src: cmp.src, attrs: cmp.attrs || {}, groups: cmp.groups || null, event: cmp.event || null,
    },
    routes: routes.map(({ src, boot, category }) => ({ src, boot: boot || null, category: category || null })),
  };
}

const runtime = (config) => `${MARK}
const CONFIG = ${literal(config)};

const params = new URLSearchParams(window.location.search);
const production = CONFIG.productionHosts.includes(window.location.host);
const on = production || params.get('martech') === 'on';
const acceptAll = !production && params.get('consent') === 'accept';

function load(src, attrs = {}) {
  const script = document.createElement('script');
  script.src = src;
  script.async = true;
  Object.entries(attrs).forEach(([name, value]) => script.setAttribute(name, value));
  document.head.append(script);
}

const BOOT = {
  gtm: () => window.dataLayer.push({ 'gtm.start': Date.now(), event: 'gtm.js' }),
  gtag: (src) => {
    window.gtag = window.gtag || function gtag() {
      // eslint-disable-next-line prefer-rest-params
      window.dataLayer.push(arguments);
    };
    window.gtag('js', new Date());
    window.gtag('config', new URL(src).searchParams.get('id'));
  },
};

const granted = (category) => acceptAll
  || String(window[CONFIG.cmp.groups] || '').split(',').includes(category);

function whenGranted(category, run) {
  if (!category || granted(category)) {
    run();
    return;
  }
  const retry = () => {
    if (!granted(category)) return;
    window.removeEventListener(CONFIG.cmp.event, retry);
    run();
  };
  window.addEventListener(CONFIG.cmp.event, retry);
}

export function loadConsent() {
  if (!on || !CONFIG.cmp?.enabled) return;
  load(CONFIG.cmp.src, CONFIG.cmp.attrs);
}

export function loadTags() {
  if (!on) return;
  CONFIG.routes.forEach(({ src, boot, category }) => whenGranted(category, () => {
    if (boot) {
      window.dataLayer = window.dataLayer || [];
      BOOT[boot](src);
    }
    load(src);
  }));
}
`;

function hook(text, fn, line) {
  if (text.includes(line)) return text;
  const open = new RegExp(`((?:async\\s+)?function ${fn}\\([^)]*\\)\\s*\\{\\n)`);
  return open.test(text) ? text.replace(open, `$1  ${line}\n`) : null;
}

const contractPath = at(CONTRACT);
if (!existsSync(contractPath)) fail(`no contract at ${contractPath} — run dynamics-plan.mjs --martech first`);
const config = configOf(JSON.parse(readFileSync(contractPath, 'utf8')));

const scripts = read('scripts/scripts.js');
if (scripts === null) fail('no scripts/scripts.js under --root');
const delayed = read('scripts/delayed.js');
const withConsent = hook(scripts, 'loadEager', CONSENT_HOOK);
if (withConsent === null) fail(`no loadEager() in scripts/scripts.js — add \`${CONSENT_HOOK}\` where the page starts loading`);
const edits = { 'scripts/martech.js': runtime(config) };
if (delayed !== null) {
  edits['scripts/scripts.js'] = withConsent;
  edits['scripts/delayed.js'] = delayed.includes(TAGS_HOOK) ? delayed : `${delayed.replace(/\n*$/, '\n')}${TAGS_HOOK}\n`;
} else {
  const withTags = hook(withConsent, 'loadDelayed', TAGS_HOOK);
  if (withTags === null) fail(`no scripts/delayed.js and no loadDelayed() in scripts/scripts.js — add \`${TAGS_HOOK}\` after the page has loaded`);
  edits['scripts/scripts.js'] = withTags;
}

const current = read('scripts/martech.js');
if (current !== null && !current.startsWith(MARK) && !FORCE) fail('scripts/martech.js exists and was not written by this scaffold — move it or pass --force');

const changed = Object.entries(edits).filter(([p, text]) => read(p) !== text);
const enabled = `${config.cmp?.enabled ? `CMP ${config.cmp.src}` : 'no CMP'} · ${config.routes.length} route(s) enabled`;
if (!changed.length) {
  console.log(`martech-scaffold: unchanged (${enabled})`);
  process.exit(0);
}
changed.forEach(([p]) => console.log(`${DRY ? 'would write' : 'write'} ${p}`));
console.log(`martech-scaffold: ${enabled}`);
if (!DRY) changed.forEach(([p, text]) => writeFileSync(at(p), text));
