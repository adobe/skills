#!/usr/bin/env node
/**
 * skills/deploy/scripts/martech-scaffold.mjs — martech contract → EDS consent + tag runtime.
 *
 * Writes under --root (edit the contract and re-run; never edit these by hand):
 *   scripts/martech-config.js   production hosts, consent policy, routes
 *   scripts/consent-check.js    host gate + CMP adapter (OneTrust, Cookiebot)
 *   scripts/consented.js        loads each enabled route whose category is granted
 *   scripts/martech.js          aem-martech / aem-gtm-martech routes, when one is enabled
 * Tags load only on contract.productionHosts. Elsewhere `?martech=on` lifts the host gate and
 * `?consent=accept|reject` stands in for the CMP.
 *
 * An enabled plugin route installs adobe-rnd/aem-martech or adobe-rnd/aem-gtm-martech with
 * `git subtree add`; until then it runs on its recorded fallback or stays off. The consent hook
 * reuses a scripts.js import of consent-check.js, else is appended to delayed.js, else inserted
 * into loadDelayed(). Files the scaffold did not write are never overwritten without --force,
 * except an empty boilerplate consent hook. Re-runs on the same contract write nothing.
 *
 *   node skills/deploy/scripts/martech-scaffold.mjs [--contract stardust/martech-contract.json]
 *        [--root .] [--dry-run] [--no-install] [--force]
 *
 *   --contract    contract path, relative to --root (default stardust/martech-contract.json)
 *   --root        the EDS project root (default .)
 *   --dry-run     report what would change; install and write nothing
 *   --no-install  never run git subtree (missing plugins use their fallback)
 *   --force       overwrite files the scaffold did not write
 *
 * Records consentHook + martechPlugins in stardust/runtime-contract.json when it exists.
 * Exit 0 written or unchanged; 1 conflict, no hook, or usage error.
 */
/* eslint-disable no-restricted-syntax, max-len */
import {
  existsSync, readFileSync, writeFileSync, mkdirSync,
} from 'node:fs';
import { join, resolve, dirname } from 'node:path';
import { spawnSync } from 'node:child_process';

if (process.argv.includes('--help') || process.argv.includes('-h')) {
  const src = readFileSync(new URL(import.meta.url), 'utf8');
  const header = src.match(/\/\*\*[\s\S]*?\*\//);
  console.log(header ? header[0].replace(/^\/\*\*\s*|\s*\*\/$/g, '').replace(/^\s*\* ?/gm, '').trim() : 'no usage header');
  process.exit(0);
}

const argv = process.argv.slice(2);
const arg = (name, dflt) => { const i = argv.indexOf(`--${name}`); return i >= 0 && argv[i + 1] && !argv[i + 1].startsWith('--') ? argv[i + 1] : dflt; };
const flag = (name) => argv.includes(`--${name}`);
const fail = (msg) => { console.error(`martech-scaffold: ${msg}`); process.exit(1); };

const ROOT = resolve(arg('root', '.'));
const CONTRACT = arg('contract', 'stardust/martech-contract.json');
const DRY = flag('dry-run');
const FORCE = flag('force');
const NO_INSTALL = flag('no-install');
const MARK = 'Generated by stardust deploy/martech-scaffold.mjs';
const HEADER = `// ${MARK} from stardust/martech-contract.json.\n// Edit the contract and re-run the scaffold; hand edits here are overwritten.\n`;
const PLUGINS = {
  'aem-martech': { dir: 'plugins/martech', repo: 'https://github.com/adobe-rnd/aem-martech.git' },
  'aem-gtm-martech': { dir: 'plugins/gtm-martech', repo: 'https://github.com/adobe-rnd/aem-gtm-martech.git' },
};
const SCRIPT_LOADERS = new Set(['url', 'gtm']);
const VENDOR_CODE = /https?:|\/\/[a-z0-9-]+\.[a-z]|loadScript|import\s*\(\s*['"](?!\.\/consented\.js)|OptanonWrapper|OneTrust|Cookiebot|usercentrics|didomi|trustarc|googletagmanager|gtag|alloy|adobedtm|_satellite|utag|fbq/i;
const IDENT = /^[A-Za-z_$][\w$]*$/;
const CONSENT_REF = /['"]\.\/consent-check\.js['"]/;
const STATIC_IMPORT = /import\s+(?:([\w$]+)\s*,?\s*)?(?:\{([^}]*)\})?\s*from\s*['"]\.\/consent-check\.js['"]/;

const at = (p) => join(ROOT, p);
const read = (p) => (existsSync(at(p)) ? readFileSync(at(p), 'utf8') : null);
const installed = (loader) => existsSync(at(join(PLUGINS[loader].dir, 'src', 'index.js')));
const stripComments = (s) => s.replace(/\/\*[\s\S]*?\*\//g, '').replace(/(^|[^:])\/\/.*$/gm, '$1');
const isPlaceholder = (s) => !VENDOR_CODE.test(stripComments(s));

function jsLiteral(v, pad = '') {
  if (v === null || v === undefined) return 'null';
  if (typeof v === 'string') return `'${v.replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\n/g, '\\n')}'`;
  if (typeof v !== 'object') return String(v);
  const inner = `${pad}  `;
  if (Array.isArray(v)) {
    if (!v.length) return '[]';
    const flat = `[${v.map((x) => jsLiteral(x)).join(', ')}]`;
    if (v.every((x) => x === null || typeof x !== 'object') && pad.length + flat.length < 80) return flat;
    return `[\n${v.map((x) => `${inner}${jsLiteral(x, inner)},`).join('\n')}\n${pad}]`;
  }
  const keys = Object.keys(v).filter((k) => v[k] !== undefined);
  if (!keys.length) return '{}';
  return `{\n${keys.map((k) => `${inner}${IDENT.test(k) ? k : jsLiteral(k)}: ${jsLiteral(v[k], inner)},`).join('\n')}\n${pad}}`;
}

function consentCheckAliases(scripts, existing) {
  const names = [];
  const m = scripts && scripts.match(STATIC_IMPORT);
  if (m && m[2]) names.push(...m[2].split(',').map((s) => s.trim().split(/\s+as\s+/)[0]));
  const src = existing ? stripComments(existing) : '';
  for (const x of src.matchAll(/export\s+(?:async\s+)?(?:function\*?|const|let|var|class)\s+([\w$]+)/g)) names.push(x[1]);
  for (const x of src.matchAll(/export\s*\{([^}]*)\}/g)) names.push(...x[1].split(',').map((s) => s.trim().split(/\s+as\s+/).pop()));
  return [...new Set(names)].filter((n) => IDENT.test(n) && n !== 'default').sort();
}

function renderConsentCheck({ selfStart, aliases }) {
  const exportsLine = aliases.length ? `export { ${aliases.map((n) => (n === 'start' ? n : `start as ${n}`)).join(', ')} };\n` : '';
  return `${HEADER}import config from './martech-config.js';

const CATEGORIES = ['analytics', 'functional', 'personalization', 'marketing'];
const params = new URLSearchParams(window.location.search);
const production = config.productionHosts.includes(window.location.host);
let started = false;
let published = '';
let applied = false;

function granted(test) {
  return Object.fromEntries(CATEGORIES.map((c) => [c, test(c)]));
}

function publish(categories) {
  const key = JSON.stringify(categories);
  if (key === published) return;
  published = key;
  window.dispatchEvent(new CustomEvent('consent.update', { detail: { categories } }));
  if (applied || Object.values(categories).some(Boolean)) {
    applied = true;
    import('./consented.js').then((m) => m.default(categories));
  }
}

function fromCmp(active) {
  const map = config.consent.categories;
  return granted((c) => Boolean(map[c]) && active.includes(map[c]));
}

function loadCmp(attrs) {
  const script = document.createElement('script');
  script.src = config.consent.src;
  Object.entries(attrs).forEach(([name, value]) => script.setAttribute(name, value));
  document.head.append(script);
}

const ADAPTERS = {
  onetrust() {
    const previous = window.OptanonWrapper;
    window.OptanonWrapper = () => {
      if (typeof previous === 'function') previous();
      publish(fromCmp(String(window.OnetrustActiveGroups || '').split(',')));
    };
    loadCmp({ 'data-domain-script': config.consent.cmpId, charset: 'UTF-8' });
  },
  cookiebot() {
    const read = () => {
      const consent = (window.Cookiebot && window.Cookiebot.consent) || {};
      publish(fromCmp(Object.keys(consent).filter((name) => consent[name] === true)));
    };
    ['CookiebotOnConsentReady', 'CookiebotOnAccept', 'CookiebotOnDecline']
      .forEach((name) => window.addEventListener(name, read));
    loadCmp({ id: 'Cookiebot', 'data-cbid': config.consent.cmpId });
  },
};

function start() {
  if (started) return;
  started = true;
  const qa = !production && params.get('martech') === 'on';
  if (!production && !qa) return;
  const override = qa && params.get('consent');
  const { policy, cmp } = config.consent;
  if (override) publish(granted(() => /^(accept|true|1|yes)$/i.test(override)));
  else if (policy === 'none-required') publish(granted(() => true));
  else if (policy === 'cmp' && ADAPTERS[cmp]) ADAPTERS[cmp]();
}
${selfStart ? '\nstart();\n' : ''}
${exportsLine}export default start;
`;
}

function renderConsented(withPlugins) {
  return `${HEADER}import config from './martech-config.js';

const started = new Set();${withPlugins ? '\nlet plugins;' : ''}

function loadScript(src) {
  return new Promise((resolve, reject) => {
    const script = document.createElement('script');
    script.src = src;
    script.async = true;
    script.onload = resolve;
    script.onerror = reject;
    document.head.append(script);
  });
}

const LOADERS = {
  url: (route) => loadScript(route.src),
  gtm: (route) => {
    const name = (route.config && route.config.dataLayerInstanceName) || 'dataLayer';
    window[name] = window[name] || [];
    window[name].push({ 'gtm.start': Date.now(), event: 'gtm.js' });
    return loadScript(route.src);
  },
};

export default async function apply(categories) {
  const routes = config.routes.filter((r) => r.enabled && categories[r.category]);
  const due = routes.filter((r) => LOADERS[r.loader] && !started.has(r.id));
  due.forEach((r) => started.add(r.id));
  const loads = due.map((r) => LOADERS[r.loader](r));${withPlugins ? `
  if (plugins || routes.some((r) => !LOADERS[r.loader])) {
    plugins = plugins || import('./martech.js');
    loads.push(plugins.then((m) => m.default(categories)));
  }` : ''}
  await Promise.allSettled(loads);
}
`;
}

function renderMartech(loaders) {
  const adobe = loaders.includes('aem-martech');
  const google = loaders.includes('aem-gtm-martech');
  const parts = [HEADER.trimEnd()];
  if (adobe) {
    parts.push(`import {
  initMartech,
  updateUserConsent,
  martechEager,
  martechLazy,
  martechDelayed,
} from '../plugins/martech/src/index.js';`);
  }
  if (google) parts.push("import * as gtmMartech from '../plugins/gtm-martech/src/index.js';");
  parts.push("import config from './martech-config.js';\n\nconst started = new Map();");
  if (adobe) {
    parts.push(`function adobeConsent(c) {
  return {
    collect: c.analytics,
    marketing: c.marketing,
    personalize: c.personalization,
    share: c.marketing,
  };
}

async function startAdobe(route, categories) {
  const { datastreamId, orgId, launchUrls } = route.config;
  await initMartech({ datastreamId, orgId }, { personalization: false, launchUrls });
  updateUserConsent(adobeConsent(categories));
  await martechEager();
  await martechLazy();
  await martechDelayed();
  return (c) => updateUserConsent(adobeConsent(c));
}`);
  }
  if (google) {
    parts.push(`function googleConsent(c) {
  const mode = (on) => (on ? 'granted' : 'denied');
  return {
    analytics_storage: mode(c.analytics),
    ad_storage: mode(c.marketing),
    ad_user_data: mode(c.marketing),
    ad_personalization: mode(c.marketing),
    functionality_storage: mode(c.functional),
    personalization_storage: mode(c.personalization),
  };
}

async function startGoogle(route, categories) {
  const GtmMartech = gtmMartech.default || gtmMartech.GtmMartech;
  const martech = new GtmMartech({
    analytics: true,
    tags: route.config.tags,
    containers: route.config.containers,
    dataLayerInstanceName: route.config.dataLayerInstanceName,
    consent: true,
    consentCallback: () => Promise.resolve(googleConsent(categories)),
  });
  await martech.eager();
  await martech.lazy();
  await martech.delayed();
  return (c) => {
    if (typeof martech.updateUserConsent === 'function') martech.updateUserConsent(googleConsent(c));
  };
}`);
  }
  parts.push(`const STARTERS = {
${adobe ? "  'aem-martech': startAdobe,\n" : ''}${google ? "  'aem-gtm-martech': startGoogle,\n" : ''}};

export default async function apply(categories) {
  const due = (r) => r.enabled && STARTERS[r.loader] && categories[r.category] && !started.has(r.id);
  config.routes.filter(due).forEach((r) => started.set(r.id, STARTERS[r.loader](r, categories)));
  const updates = [...started.values()].map((p) => p.then((update) => update(categories)));
  await Promise.allSettled(updates);
}
`);
  return parts.join('\n\n');
}

function hookPlan() {
  const scripts = read('scripts/scripts.js');
  const delayed = read('scripts/delayed.js');
  if (scripts && CONSENT_REF.test(scripts)) {
    const m = scripts.match(STATIC_IMPORT);
    return { hook: 'consent-check', where: 'scripts.js imports consent-check.js', selfStart: !(m && (m[1] || m[2])) };
  }
  if (delayed !== null && CONSENT_REF.test(delayed)) return { hook: 'delayed-js', where: 'delayed.js imports consent-check.js', selfStart: true };
  if (delayed !== null) {
    const body = delayed.trimEnd();
    return { hook: 'delayed-js', where: 'import appended to delayed.js', selfStart: true, edit: { file: 'scripts/delayed.js', text: `${body ? `${body}\n\n` : ''}import('./consent-check.js');\n` } };
  }
  const loadDelayed = /(function loadDelayed\(\)\s*\{[^\n]*\n)/;
  if (scripts && loadDelayed.test(scripts)) return { hook: 'consent-check', where: 'import inserted into loadDelayed()', selfStart: true, edit: { file: 'scripts/scripts.js', text: scripts.replace(loadDelayed, "$1  import('./consent-check.js');\n") } };
  return { hook: 'none' };
}

let contract;
try { contract = JSON.parse(readFileSync(join(ROOT, CONTRACT), 'utf8')); } catch (e) { fail(`cannot read ${CONTRACT}: ${e.message}`); }
if (contract?.version !== 1 || !Array.isArray(contract.routes) || !contract.consent) fail(`${CONTRACT} is not a version 1 martech contract`);

const notes = [];
const wanted = [...new Set(contract.routes.filter((r) => r.enabled && PLUGINS[r.loader]).map((r) => r.loader))];
for (const loader of wanted.filter((l) => !installed(l))) {
  const { dir, repo } = PLUGINS[loader];
  const gitArgs = ['subtree', 'add', '--squash', '--prefix', dir, repo, 'main'];
  const cmd = `git ${gitArgs.join(' ')}`;
  if (DRY || NO_INSTALL) notes.push(`${loader} not installed — to install: ${cmd}`);
  else {
    const r = spawnSync('git', gitArgs, { cwd: ROOT, encoding: 'utf8' });
    if (r.status !== 0) notes.push(`${loader} install failed (${String(r.stderr || '').trim().split('\n').pop()}) — run: ${cmd}`);
  }
}

const routes = contract.routes.map((r) => {
  const out = { id: r.id, loader: r.loader, src: r.src || null, config: r.config || null, category: r.category || 'analytics', enabled: Boolean(r.enabled) };
  if (!out.enabled) return out;
  if (PLUGINS[r.loader] && !installed(r.loader)) {
    if (r.fallback && SCRIPT_LOADERS.has(r.fallback.loader) && r.fallback.src) {
      notes.push(`${r.id}: runs on its fallback (${r.fallback.loader} ${r.fallback.src}) until ${r.loader} is installed`);
      return { ...out, loader: r.fallback.loader, src: r.fallback.src, config: r.fallback.config || null };
    }
    notes.push(`${r.id}: off until ${r.loader} is installed`);
    return { ...out, enabled: false };
  }
  if (!PLUGINS[r.loader] && !(SCRIPT_LOADERS.has(r.loader) && out.src)) {
    notes.push(`${r.id}: off — loader "${r.loader}" needs a src`);
    return { ...out, enabled: false };
  }
  return out;
});
const pluginLoaders = Object.keys(PLUGINS).filter((l) => routes.some((r) => r.enabled && r.loader === l));

const hook = hookPlan();
if (hook.hook === 'none') fail('no consent hook: scripts/scripts.js has no loadDelayed() and there is no scripts/delayed.js');
const { cmp, cmpId, src, policy, categories } = contract.consent;
const runtime = { productionHosts: contract.productionHosts || [], consent: { cmp, cmpId, src, policy, categories }, routes };
const files = [
  { path: 'scripts/martech-config.js', text: `${HEADER}export default ${jsLiteral(runtime)};\n` },
  { path: 'scripts/consent-check.js', text: renderConsentCheck({ selfStart: hook.selfStart, aliases: consentCheckAliases(read('scripts/scripts.js'), read('scripts/consent-check.js')) }), placeholder: true },
  { path: 'scripts/consented.js', text: renderConsented(pluginLoaders.length > 0), placeholder: true },
  ...(pluginLoaders.length ? [{ path: 'scripts/martech.js', text: renderMartech(pluginLoaders) }] : []),
];
for (const f of files) {
  const cur = read(f.path);
  if (cur === null) f.action = 'create';
  else if (cur === f.text) f.action = 'unchanged';
  else if (cur.includes(MARK) || (f.placeholder && isPlaceholder(cur))) f.action = 'update';
  else f.action = FORCE ? 'overwrite' : 'conflict';
}
const conflicts = files.filter((f) => f.action === 'conflict');

const eslintIgnore = read('.eslintignore');
const pluginDirs = Object.keys(PLUGINS).filter(installed).map((l) => PLUGINS[l].dir);
const edits = hook.edit ? [hook.edit] : [];
if (pluginDirs.length && eslintIgnore !== null && !/^\/?plugins\/?(\*\*)?\s*$/m.test(eslintIgnore)) edits.push({ file: '.eslintignore', text: `${eslintIgnore.trimEnd()}\nplugins/\n` });
const rcPath = 'stardust/runtime-contract.json';
const rc = read(rcPath);
if (rc !== null) {
  const next = `${JSON.stringify({ ...JSON.parse(rc), consentHook: hook.hook, martechPlugins: pluginDirs }, null, 2)}\n`;
  if (next !== rc) edits.push({ file: rcPath, text: next });
}

console.log(`martech-scaffold: ${(contract.stack || []).join(' · ') || 'no martech stack'}${DRY ? ' (dry run)' : ''}`);
console.log(`  hook: ${hook.hook} — ${hook.where}`);
for (const f of files) console.log(`  ${f.path}: ${f.action}`);
for (const e of edits) console.log(`  ${e.file}: update`);
for (const r of routes) console.log(`  route ${r.id}: ${r.loader} · ${r.category} · ${r.enabled ? 'on' : 'off'}`);
console.log(`  consent: ${policy}${cmp ? ` (${cmp})` : ''} · production hosts: ${runtime.productionHosts.join(', ') || 'none — tags never load'}`);
for (const n of notes) console.log(`  note: ${n}`);
if (conflicts.length) fail(`not overwriting ${conflicts.map((f) => f.path).join(', ')} — not written by this scaffold; merge by hand or re-run with --force`);
if (DRY) process.exit(0);

for (const f of files.filter((x) => ['create', 'update', 'overwrite'].includes(x.action))) {
  mkdirSync(dirname(at(f.path)), { recursive: true });
  writeFileSync(at(f.path), f.text);
}
for (const e of edits) writeFileSync(at(e.file), e.text);
